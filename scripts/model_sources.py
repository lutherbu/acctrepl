#!/usr/bin/env python3
"""Recover a model's base specification and optional source regions using its own recorded inputs."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import tempfile
import os

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import project_layout as layout


def regions(node):
    if isinstance(node, dict):
        if 'crop_sha256' in node:
            yield node
        else:
            for child in node.values():
                yield from regions(child)
    elif isinstance(node, list):
        for child in node:
            yield from regions(child)


def save(root, ref, data, check=False):
    dest = layout.artifact_path(ref['path'], root)
    if not dest.is_relative_to(root / '.local'):
        raise ValueError(f'Expected a cache destination: {dest}')
    if hashlib.sha256(data).hexdigest() != ref['sha256']:
        raise ValueError(f'Generated bytes differ from the model record: {dest}')
    if dest.is_file() and layout.sha(dest) == ref['sha256']:
        return
    if check:
        raise ValueError(f'Missing or stale cache file: {dest}')
    dest.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=dest.parent) as tmp:
        f = Path(tmp) / 'payload'
        f.write_bytes(data)
        os.replace(f, dest)


def materialize(record, *, root=ROOT, crops=False, check=False, verify_inputs=False):
    from importlib.util import spec_from_file_location, module_from_spec
    spec = spec_from_file_location('model_validation', root / 'skills/extract-accounting-models/scripts/validate_results.py')
    validator = module_from_spec(spec)
    spec.loader.exec_module(validator)
    base = validator.project_v1(layout.legacy_model(record, root))
    data = (json.dumps(base, indent=2, ensure_ascii=False) + '\n').encode()
    save(root, record['base_specification'], data, check)
    if not (verify_inputs or crops):
        return
    refs = record['source_inputs']
    for name in ('reading', 'pdf'):
        path = layout.artifact_path(refs[name]['path'], root)
        if not path.is_file() or layout.sha(path) != refs[name]['sha256']:
            raise ValueError(f'Supply the pinned {name}: {path}')
    if crops:
        import pymupdf
        seen = set()
        with pymupdf.open(layout.artifact_path(refs['pdf']['path'], root)) as pdf:
            for ev in regions(record):
                digest = ev['crop_sha256']
                if digest in seen:
                    continue
                seen.add(digest)
                if ev['pdf_sha256'] != refs['pdf']['sha256'] or not 1 <= ev['page'] <= len(pdf):
                    raise ValueError('Region is bound to a different PDF or page')
                clip = pymupdf.Rect(ev['bbox'])
                page = pdf[ev['page'] - 1]
                if clip.is_empty or not page.rect.contains(clip) or not 0 < ev['scale'] <= 8:
                    raise ValueError('Invalid PDF region')
                payload = page.get_pixmap(matrix=pymupdf.Matrix(ev['scale'], ev['scale']), clip=clip, alpha=False).tobytes('png')
                save(root, {'path':ev['crop_path'], 'sha256':digest}, payload, check)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('paper_ids', nargs='+')
    ap.add_argument('--crops', action='store_true')
    ap.add_argument('--verify-inputs', action='store_true')
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    for pid in a.paper_ids:
        if not pid or Path(pid).name != pid:
            ap.error('Expected a paper ID')
        p = ROOT / 'output/models/records' / (pid + '.json')
        materialize(json.loads(p.read_bytes()), crops=a.crops, check=a.check, verify_inputs=a.verify_inputs)
        print(pid)


if __name__ == '__main__':
    main()
